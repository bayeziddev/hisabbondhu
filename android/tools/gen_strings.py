#!/usr/bin/env python3
"""Generates values/strings.xml (English) and values-bn/strings.xml (Bangla) from strings_source.py."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from strings_source import S

RES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "src", "main", "res")

def esc(v: str) -> str:
    v = v.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    v = v.replace("'", "\\'").replace('"', '\\"')
    if v.startswith("@") or v.startswith("?"):
        v = "\\" + v
    return v

def write(folder: str, idx: int):
    os.makedirs(os.path.join(RES, folder), exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- GENERATED by tools/gen_strings.py — edit tools/strings_source.py instead -->',
             '<resources>']
    for k, pair in S.items():
        v = pair[idx]
        attrs = ""
        if k == "app_name" and idx == 0:
            attrs = ' translatable="false"' if False else ""
        if "%" in v and not re.search(r"%\d\$", v):
            attrs += ' formatted="false"'
        lines.append(f'    <string name="{k}"{attrs}>{esc(v)}</string>')
    lines.append('</resources>')
    with open(os.path.join(RES, folder, "strings.xml"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

write("values", 0)
write("values-bn", 1)

# Verify every key used in Kotlin exists.
src = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "src", "main", "java")
used = set()
for root, _, files in os.walk(src):
    for fn in files:
        if fn.endswith(".kt"):
            used |= set(re.findall(r"R\.string\.([A-Za-z0-9_]+)", open(os.path.join(root, fn), encoding="utf-8").read()))
missing = sorted(used - set(S))
unused = sorted(set(S) - used)
for k, (en, bn) in S.items():
    a = sorted(set(re.findall(r"%\d\$s", en))); b = sorted(set(re.findall(r"%\d\$s", bn)))
    if a != b:
        print(f"PLACEHOLDER MISMATCH {k}: {a} vs {b}")
print(f"{len(S)} strings written. missing={missing} unused={unused}")
sys.exit(1 if missing else 0)
